#!/bin/zsh
# Release packaging for the binary SDK (run after tools/build_xcframework.sh):
#   dist/NPCVoiceKit-<version>.xcframework.zip   the xcframework alone (SwiftPM binaryTarget)
#   dist/NPCVoiceKit-<version>-sdk.zip           xcframework + CMake package config (C/C++)
#   dist/Package.swift                           SwiftPM binaryTarget pointing at the first zip
# Model weights are separate assets (tools/package_models.sh).
# The zip goes to the GitHub release "v<version>"; the manifest's URL is derived from the
# origin remote (override with NPCVOICE_RELEASE_URL=<base URL>).
set -euo pipefail
cd "$(dirname "$0")/.."
version=$(awk -F'"' '/MARKETING_VERSION/ {print $2; exit}' project.yml)
[[ -d dist/NPCVoiceKit.xcframework ]] || { print -u2 "run tools/build_xcframework.sh first"; exit 1; }
zip=dist/NPCVoiceKit-$version.xcframework.zip
sdk=dist/NPCVoiceKit-$version-sdk.zip
stage=$(mktemp -d)
cp -R dist/NPCVoiceKit.xcframework "$stage/"
cp cmake/NPCVoiceKitConfig.cmake cmake/NPCVoiceKitConfigVersion.cmake "$stage/"
rm -f "$zip" "$sdk"
(cd "$stage" && COPYFILE_DISABLE=1 zip -qry "$OLDPWD/$zip" NPCVoiceKit.xcframework \
             && COPYFILE_DISABLE=1 zip -qry "$OLDPWD/$sdk" NPCVoiceKit.xcframework NPCVoiceKitConfig.cmake NPCVoiceKitConfigVersion.cmake)
rm -rf "${stage:?}"
checksum=$(swift package compute-checksum "$zip")

base=${NPCVOICE_RELEASE_URL:-}
if [[ -z $base ]]; then
  origin=$(git remote get-url origin 2>/dev/null || true)
  if [[ $origin =~ 'github\.com[:/]([^/]+)/([^/.]+)' ]]; then
    base="https://github.com/${match[1]}/${match[2]}/releases/download/v$version"
  else
    base="https://github.com/OWNER/REPO/releases/download/v$version"
    print -u2 "note: no GitHub origin remote; edit the URL in dist/Package.swift"
  fi
fi
cat > dist/Package.swift <<SWIFT
// swift-tools-version: 6.0
// Binary distribution of NPCVoiceKit $version (generated by tools/package_sdk.sh).
import PackageDescription

let package = Package(
    name: "NPCVoiceKit",
    platforms: [.macOS("27.0")],
    products: [.library(name: "NPCVoiceKit", targets: ["NPCVoiceKit"])],
    targets: [
        .binaryTarget(
            name: "NPCVoiceKit",
            url: "$base/${zip:t}",
            checksum: "$checksum"),
    ]
)
SWIFT
print "$zip ($(du -h "$zip" | cut -f1)), checksum $checksum"
print "$sdk ($(du -h "$sdk" | cut -f1))"
print "dist/Package.swift -> $base/${zip:t}"
