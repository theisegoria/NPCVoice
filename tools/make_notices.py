#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md from the vendored license files (exact texts), plus the
model credits. Run after updating anything in third_party/: python3 -I tools/make_notices.py"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
tp = root / "third_party"

code = [  # (name, use, license, license file, notice file)
    ("mlx-swift 0.32.3", "GPU array framework (dialogue model)", "MIT", "mlx-swift/LICENSE", None),
    ("MLX (C++)", "inside mlx-swift", "MIT", "mlx-swift/Source/Cmlx/mlx/LICENSE", None),
    ("mlx-c", "inside mlx-swift", "MIT", "mlx-swift/Source/Cmlx/mlx-c/LICENSE", None),
    ("{fmt}", "inside mlx-swift", "MIT", "mlx-swift/Source/Cmlx/fmt/LICENSE", None),
    ("JSON for Modern C++", "inside mlx-swift", "MIT", "mlx-swift/Source/Cmlx/json/LICENSE.MIT", None),
    ("metal-cpp", "inside mlx-swift", "Apache-2.0", "mlx-swift/Source/Cmlx/metal-cpp/LICENSE.txt", None),
    ("mlx-swift-lm 3.32.3", "language model loading and guided generation (patched)", "MIT", "mlx-swift-lm/LICENSE", None),
    ("XGrammar", "grammar-constrained decoding, inside mlx-swift-lm (patched shim)", "Apache-2.0",
     "mlx-swift-lm/Libraries/MLXCXGrammar/xgrammar/LICENSE", "mlx-swift-lm/Libraries/MLXCXGrammar/xgrammar/NOTICE"),
    ("swift-numerics 1.1.1", "dependency of mlx-swift", "Apache-2.0 with Runtime Library Exception", "swift-numerics/LICENSE.txt", None),
]

# Copyright holders stated in the sources rather than the license file.
extra = {
    "swift-numerics 1.1.1": ["Copyright (c) 2019-2025 Apple Inc. and the Swift Numerics project authors"],
}

out = ["# Third-party notices",
       "",
       "NPCVoice is licensed under the Apache License 2.0 (see `LICENSE` and `NOTICE`). It includes or",
       "downloads the components below. Generated by `tools/make_notices.py`; don't edit by hand.",
       "",
       "## Models (downloaded by `tools/fetch_models.sh`, bundled in release builds)",
       "",
       "| Model | License | Notes |",
       "|---|---|---|",
       "| [Qwen3.5-2B](https://huggingface.co/Qwen/Qwen3.5-2B), 4-bit MLX conversion by [mlx-community](https://huggingface.co/mlx-community/Qwen3.5-2B-4bit) | Apache-2.0 | By the Qwen team (Alibaba Cloud) |",
       "| [Kokoro-82M](https://huggingface.co/hexgrad/Kokoro-82M) v1.0 | Apache-2.0 | By hexgrad. Converted to Core ML (fp32) by `tools/convert_kokoro_coreml.py`, whose graph rewrites preserve its output |",
       "| [misaki](https://github.com/hexgrad/misaki) 0.9.4 English lexicons and Japanese tables | Apache-2.0 | By hexgrad. NPCVoice's English and Japanese G2P are Swift ports of misaki |",
       "| [cutlet](https://github.com/polm/cutlet) | MIT | misaki's `cutlet.py` (romanization rules and kana table), which NPCVoice's Japanese G2P ports, is adapted from cutlet by Paul O'Leary McCann |",
       "",
       "**Voice credits (CC BY).** The Japanese voices `jf_tebukuro` and `jm_kumo` were trained on",
       "readings from the [Koniwa](https://github.com/koniwa/koniwa) project, licensed",
       "[CC BY 3.0](https://creativecommons.org/licenses/by/3.0/): \"tebukurowokaini\" and \"kumonoito\"",
       "(`tnc` readings). Kokoro v1.0's training data also included Koniwa (CC BY 3.0) and",
       "[SIWIS](https://datashare.ed.ac.uk/handle/10283/2353) (CC BY 4.0) audio. Games that ship",
       "these voices should carry this credit.",
       "",
       "## Code",
       ""]
for name, use, lic, path, notice in code:
    out += [f"### {name}", "", f"{use[0].upper() + use[1:]}. License: {lic}.", ""]
    text = (tp / path).read_text().strip()
    if lic.startswith("Apache"):
        out += ["The Apache License 2.0 text is in `LICENSE`."]
        holders = [l.strip() for l in text.splitlines() if re.match(r"\s*(Copyright\s*(\(c\)|©|\d)|Copyright \d)", l)]
        holders += extra.get(name, [])
        if holders: out += ["", *[f"> {l}" for l in holders[:3]]]
        if "Runtime Library Exception" in text:
            tail = text[text.index("## Runtime Library Exception"):] if "## Runtime Library Exception" in text else ""
            if tail: out += ["", "```", tail, "```"]
    else:
        out += ["```", text, "```"]
    if notice:
        out += ["", "NOTICE:", "", "```", (tp / notice).read_text().strip(), "```"]
    out.append("")
(root / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out) + "\n")
print("wrote THIRD_PARTY_NOTICES.md")
